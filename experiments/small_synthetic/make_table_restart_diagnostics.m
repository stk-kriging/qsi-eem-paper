% Table SM2 of the supplement, restart diagnostics of the SMC safeguard,
% from the level logs written by qsi_eem_smc, whose header documents the
% event codes.  Covers every test case at once.

close all;

fprintf ('Making restart diagnostics table\n');

script_dir = fileparts (mfilename ('fullpath'));

data_dir  = fullfile (script_dir, 'outputs', 'results');
input_dir = fullfile (data_dir, 'smc_logs');
table_dir = fullfile (data_dir, 'tables');

if ~ isfolder (table_dir)
    mkdir (table_dir);
end

% name in the data files, name of the test case in the paper
cases = { ...
    'piston_smc', 'Piston' ; ...
    'trid_smc',   '$7$-Trid' ; ...
    'otl_smc',    'OTL' };

batch_sizes = [1 2 3];
run_ids = 1:100;

event_column = 2;
activation_events = [2 3 4 5 6];
restart_events = [2 3 4]; % 6 refreshes the population, not the level sequence

rows = {};

for c = 1:size (cases, 1)
    for b = batch_sizes

        nb_runs = 0;
        nb_with = 0;
        nb_activations = 0;
        nb_restarts = 0;

        for it = run_ids
            f = fullfile (input_dir, sprintf ('log_QSI_EEM_smc_%s_%d_%d.csv', ...
                cases{c,1}, it, b));
            if ~ isfile (f)
                continue
            end
            level_log = readmatrix_ (f);
            events = level_log(:, event_column);

            nb_runs = nb_runs + 1;
            a = sum (ismember (events, activation_events));
            nb_activations = nb_activations + a;
            nb_restarts = nb_restarts + sum (ismember (events, restart_events));
            nb_with = nb_with + (a > 0);
        end

        if nb_runs == 0
            fprintf ('  %-11s batch %d: no log, skipped\n', cases{c,1}, b);
            continue
        end

        rows(end+1, :) = {cases{c,2}, b, nb_runs, nb_with, ...
            nb_activations, nb_restarts};  %#ok<SAGROW>

    end
end

if isempty (rows)
    error ('No log found in %s.', input_dir);
end

nb_runs_total = sum (cell2mat (rows(:,3)));
fprintf ('\n%d run(s) over %d line(s) of the table\n', nb_runs_total, size (rows, 1));

% LaTeX

tex_file = fullfile (table_dir, 'table_restart_diagnostics.tex');

fid = fopen (tex_file, 'wt');
if fid < 0
    error ('Cannot open %s for writing.', tex_file);
end

fprintf (fid, '%% Generated by make_table_restart_diagnostics.m\n');
fprintf (fid, '\\begin{table}[h]\n');
fprintf (fid, '  \\centering\n');
fprintf (fid, ['  \\caption{Restart diagnostics over %d runs for each ' ...
    'test case and\n    batch size. A run may activate the safeguard ' ...
    'more than once.}\n'], max (cell2mat (rows(:,3))));
fprintf (fid, '  \\label{eem:tab:restart_diagnostics}\n');
fprintf (fid, '  \\begin{tabular}{lcccc}\n');
fprintf (fid, '    \\hline\n');
fprintf (fid, ['    Test case & Batch size & Runs with activation & ' ...
    'Activations & Restarts \\\\\n']);
fprintf (fid, '    \\hline\n');

previous = '';
for r = 1:size (rows, 1)
    if strcmp (rows{r,1}, previous)
        name = '       ';
    else
        name = rows{r,1};
        previous = rows{r,1};
    end
    fprintf (fid, '    %s & $%d$ & $%d$ & $%d$ & $%d$ \\\\\n', ...
        name, rows{r,2}, rows{r,4}, rows{r,5}, rows{r,6});
end

fprintf (fid, '    \\hline\n');
fprintf (fid, '  \\end{tabular}\n');
fprintf (fid, '\\end{table}\n');

fclose (fid);
fprintf ('Wrote %s\n', tex_file);

% Console

fprintf ('\n  %-10s %6s %8s %12s %10s\n', ...
    'Test case', 'Batch', 'Runs', 'Activations', 'Restarts');
for r = 1:size (rows, 1)
    fprintf ('  %-10s %6d %8d %12d %10d\n', ...
        strrep (strrep (rows{r,1}, '$', ''), '\', ''), ...
        rows{r,2}, rows{r,4}, rows{r,5}, rows{r,6});
end

fprintf ('\n  total: %d activation(s), %d restart(s)\n', ...
    sum (cell2mat (rows(:,5))), sum (cell2mat (rows(:,6))));

fprintf ('\nDone.\n');
