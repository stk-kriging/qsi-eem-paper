% Runtime table of Section 4.3, from the timings written by
% run_total_time_comparison.  One row per measure, one column per
% algorithm.

close all;

fprintf ('Making the criterion runtime tables\n');

script_dir = fileparts (mfilename ('fullpath'));

input_dir = fullfile (script_dir, 'outputs', 'results', 'time');
table_dir = fullfile (script_dir, 'outputs', 'results', 'tables');

if ~ isfolder (table_dir)
    mkdir (table_dir);
end

if ~ isfolder (input_dir)
    error (['No timings found in %s.\n' ...
        'Run run_total_time_comparison first.'], input_dir);
end

nb_runs = 10;

% name in the data files, name of the test case in Section 4.3
cases = { ...
    'branin_mod',   '$f_1$' };

% name in the data files, column heading
algos = { ...
    'Ranjan',            'Ranjan' ; ...
    'misclassification', 'misclass.' ; ...
    'joint_m',           'Joint-SUR' ; ...
    'QSI_m',             'QSI-SUR' ; ...
    'QSI_EEM',           'QSI-EEM' };

reference = 'Ranjan';   % normalization of the total runtime

nb_cases = size (cases, 1);
nb_algos = size (algos, 1);

first_time = nan (nb_cases, nb_algos);
total_time = nan (nb_cases, nb_algos);
nb_seen = zeros (nb_cases, nb_algos);

for c = 1:nb_cases
    for a = 1:nb_algos
        t = load_timings (input_dir, algos{a,1}, cases{c,1}, nb_runs);
        if isempty (t)
            continue
        end
        nb_seen(c,a) = size (t, 1);
        first_time(c,a) = mean (t(:,1));
        total_time(c,a) = mean (sum (t, 2));
    end
end

% Rows and columns that carry no data at all are dropped
keep_c = any (nb_seen > 0, 2);
keep_a = any (nb_seen > 0, 1);

if ~ any (keep_c) || ~ any (keep_a)
    error (['No timings found in %s.\n' ...
        'Run run_total_time_comparison first.'], input_dir);
end

ref_a = find (strcmp (reference, algos(:,1)), 1);
if isempty (ref_a) || ~ keep_a(ref_a)
    error ('No timings for the reference algorithm %s.', reference);
end

relative_time = total_time ./ total_time(:,ref_a);

fprintf ('\n%d test case(s), %d algorithm(s), %d run(s) each\n', ...
    sum (keep_c), sum (keep_a), max (nb_seen(:)));

measures = { ...
    'First design step (s)',   first_time(keep_c,keep_a) ; ...
    'Total runtime, relative', relative_time(keep_c,keep_a) };

write_table (table_dir, 'table_runtime', measures, algos(keep_a,2), 2, ...
    sprintf (['Runtime of the sampling criteria on %s: the first ' ...
    'sequential design\n    step after the initial design, in seconds, ' ...
    'and the total runtime of a\n    run, normalized so that the %s ' ...
    'runtime is equal to one.  Average over\n    %d~runs.'], ...
    cases{find(keep_c, 1), 2}, reference, max (nb_seen(:))), ...
    'eem:table:runtime');

fprintf ('\nDone.\n');


function t = load_timings (input_dir, algo_name, case_name, nb_runs)

t = [];

for it = 1:nb_runs
    f = fullfile (input_dir, ...
        sprintf ('time_%s_%s_%d.csv', algo_name, case_name, it));
    if ~ isfile (f)
        continue
    end
    row = readmatrix_ (f);
    t = [t; row(:)'];  %#ok<AGROW>
end

end % function


function write_table (table_dir, name, measures, col_names, nb_digits, ...
    caption, label)

% measures: {label, row}, one table line each, one value per algorithm

nb_measures = size (measures, 1);
nb_algos = numel (col_names);

tex_file = fullfile (table_dir, [name '.tex']);

fid = fopen (tex_file, 'wt');
if fid < 0
    error ('Cannot open %s for writing.', tex_file);
end

fprintf (fid, '%% Generated by make_tables_total_time_comparison.m\n');
fprintf (fid, '\\begin{table}[ht]\n');
fprintf (fid, '  \\centering\n');
fprintf (fid, '  \\begin{tabular}{l|%s}\n', repmat ('c |', 1, nb_algos));
fprintf (fid, '    \\cline{2-%d}\n', nb_algos + 1);
fprintf (fid, '   ');
fprintf (fid, ' & %s', col_names{:});
fprintf (fid, ' \\\\\n    \\hline\n');

for m = 1:nb_measures
    fprintf (fid, '    \\multicolumn{1}{|l|}{%s}', measures{m,1});
    for k = 1:nb_algos
        fprintf (fid, ' & %s', fmt_value (measures{m,2}(k), nb_digits));
    end
    fprintf (fid, ' \\\\\n    \\hline\n');
end

fprintf (fid, '  \\end{tabular}\n');
fprintf (fid, '  \\caption{%%\n    %s}\n', caption);
fprintf (fid, '  \\label{%s}\n', label);
fprintf (fid, '\\end{table}\n');

fclose (fid);
fprintf ('Wrote %s\n', tex_file);

% Console

fprintf ('\n  %-26s', '');
fprintf ('%12s', col_names{:});
fprintf ('\n');
for m = 1:nb_measures
    fprintf ('  %-26s', measures{m,1});
    for k = 1:nb_algos
        fprintf ('%12s', fmt_value (measures{m,2}(k), nb_digits));
    end
    fprintf ('\n');
end

end % function


function s = fmt_value (v, nb_digits)

if ~ isfinite (v)
    s = '--';
elseif abs (v - 1) < 1e-12
    s = '1';
else
    s = sprintf ('%.*f', nb_digits, v);
end

end % function
